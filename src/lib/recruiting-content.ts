export function informationReply(input: string): FlowReply | null {
  const result = informationContent(input);
  if (!result) return null;
  const url = result.text.match(/https:\/\/[^\s]+/)?.[0];
  if (url) result.choices.unshift({ label: "公式ページを開く", text: "", uri: url });
  return result;
}
